const MUSIC = { town: { bpm: 72, state: 'quiet' } };

function room(id, c0, c1, extra = {}) {
  return {
    id,
    section: extra.road ? 'road' : 'town',
    finale: true,
    allowNoFoes: true,
    grid: slice(c0, c1),
    music: MUSIC.town,
    bg: { landmark: id },
    ...extra,
    // (`to` stays a WORLD column: RoomBuilder only offsets x)
    objects: [...(O[id] || []), ...FINDS.filter((f) => f.at >= c0 && f.at <= c1).map((f) => ({ type: 'find', ...f }))].map(({ at, ...o }) => ({ ...o, x: at - c0 })),
  };
}

export default [
  room('meadow_w', 0, EV.BUF - 1),
  ...PLACES.map((p) => room(p.id, p.c0, p.c1, p.id === 'hill' ? { vista: true } : {})),
  room('meadow_e', EV.E0, EV.R0 - 1),
  ...ROAD.map((p) => room(p.id, p.c0, p.c1, { road: true, vista: p.id === 'ridge' })),
];
