import { buildPainterMap } from './map.js';

// D2 — rooms = grid + objects. Objects are written in WORLD columns and
// shifted to room-local ones here. Object types the PainterScene knows:
//   pickup {colour}        a pigment tube on the ground
//   letter {id, tubes}     one of Isak's letters (readable; tubes inside)
//   surface {id, x1, h, accepts} a paintable rectangle of the world (walls, sky, a channel…)
//   subject {id}           a subject marker (data/painter/subjects.js)
//   easel {id}             set up the easel: capture / sleep
//   panel {puzzle}         a puzzle-box
//   dark {x1, h}           a room that is dark until yellow lights it
//   wind                   the Mistral blows through this room (strength)
//   bud / lock / bridge / vine / stove / chair / shutter / bell / current / star / moon …
const FULL = buildPainterMap();
const slice = (x0, x1) => FULL.map((row) => row.slice(x0, x1 + 1));

function room(def, x0, x1, objects) {
  return {
    ...def,
    grid: slice(x0, x1),
    objects: objects.map((o) => ({
      ...o,
      x: o.x - x0,
      patrol: o.patrol ? o.patrol.map((c) => c - x0) : undefined,
      x1: o.x1 !== undefined ? o.x1 - x0 : undefined,
      pts: o.pts ? o.pts.map(([px, py]) => [px - x0, py]) : undefined,
    })),
  };
}

